	#[test]
	fn every_bundled_licence_is_one_we_may_redistribute() {
		// The list from HANDOVER-kaitai.md. A `.ksy` under anything else is
		// not copied into this repository at all, so this failing means a file
		// arrived without the check being run.
		const ALLOWED: &[&str] =
			&["CC0-1.0", "MIT", "Unlicense", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause"];
		for entry in BUNDLED {
			assert!(
				ALLOWED.contains(&entry.licence),
				"{} is {}, which is not a licence this ships under",
				entry.id,
				entry.licence
			);
		}
	}

	#[test]
	fn an_import_finds_the_file_by_path_or_by_name() {
		assert!(BundledImports.load("/common/vlq_base128_le").is_some());
		assert!(BundledImports.load("common/vlq_base128_le").is_some());
		assert!(BundledImports.load("vlq_base128_le").is_some());
		assert!(BundledImports.load("nothing_by_that_name").is_none());
	}
