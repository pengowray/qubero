//! The Kaitai Struct format descriptions shipped inside Qubero.
//!
//! Every `.ksy` under `crates/core/formats-ksy` is a verbatim copy of a file
//! from the Kaitai Struct format library, compiled in with `include_str!` and
//! converted on demand. A bundled format is opened by a name like `ksy:png`,
//! and once converted it is a [`Template`](crate::template::Template) like any
//! other: nothing about it is Kaitai at run time.
//!
//! Which files are here, and why each one is, is
//! `crates/core/formats-ksy/README.md`. The short version: the licence has to
//! be one a redistributor can meet, and the conversion has to reach the bytes
//! a reader opens the file for. A format whose gaps are in a rare instance
//! ships with the gaps showing in the panel; one whose gaps are on the path
//! through the file does not ship at all.
//!
//! The table below is generated. `node tools/ksy_bundle.mjs` rewrites it and
//! the README from the directory, so adding a format is: copy the `.ksy` in,
//! run the script, run the tests.

use super::imports::Imports;
use super::lower::{convert, Converted};
use super::yaml::KsyError;

/// One shipped `.ksy`.
pub struct Bundled {
	/// `meta/id`, which is also what `ksy:<id>` opens.
	pub id: &'static str,
	/// The id with [`PREFIX`] on the front, which is the name a caller opens
	/// this by and the name [`sniff`] answers with. Written out rather than
	/// joined, because a sniffer answers with a `&'static str`.
	pub name: &'static str,
	/// The directory it sits in, which is the Kaitai library's own grouping:
	/// `image`, `network`, `common` and so on.
	pub category: &'static str,
	/// `meta/title`, empty for the files that carry none. Nothing invents one:
	/// a format with no title is shown by its id.
	pub title: &'static str,
	/// `meta/license`, as an SPDX identifier.
	pub licence: &'static str,
	/// Where this file came from, relative to the root of the Kaitai Struct
	/// format library. Also what an import naming a path resolves against.
	pub source: &'static str,
	/// The file, byte for byte.
	pub text: &'static str,
	/// Whether a reader may open a file as this. False for a file that is here
	/// only to be imported by another, and for a root type that takes
	/// parameters, which has no meaning without arguments nobody can supply.
	pub offered: bool,
	/// What a file of this format opens with, as `(offset, bytes)` pairs: the
	/// `contents` the format reads first, found through nested types, and
	/// every further `contents` reachable through fields of a fixed width.
	/// Derived by [`signature`](super::signature). See [`sniff`].
	pub signature: &'static [(u64, &'static [u8])],
	/// Whether [`sniff`] offers this format for a dropped file. False for a
	/// format with no leading magic, and for one whose magic another bundled
	/// format also claims.
	pub sniffs: bool,
	/// `meta/file-extension`, lower case and without the dot. What tells
	/// apart two formats whose bytes are the same: see [`sniff_named`].
	pub extensions: &'static [&'static str],
}

/// The name a bundled format is opened by. `ksy:` and the `meta/id`.
pub const PREFIX: &str = "ksy:";

/// The ids a reader may open a file as, in the order the table lists them.
/// Files that are here only to be imported are not among them.
pub fn names() -> Vec<&'static str> {
	BUNDLED.iter().filter(|b| b.offered).map(|b| b.id).collect()
}

/// The whole shipped collection, imports and all.
pub fn all() -> &'static [Bundled] {
	BUNDLED
}

/// One entry by its `meta/id`, whether or not it is offered.
pub fn find(id: &str) -> Option<&'static Bundled> {
	BUNDLED.iter().find(|b| b.id == id)
}

/// Convert a bundled format, imports resolved against the rest of the
/// collection. `None` for an id nothing here has.
///
/// The conversion happens now rather than at build time: the IR is Rust and
/// never serialised, so there is nothing to bake. It is a few milliseconds for
/// the largest of them, paid when a reader picks the format.
///
/// The [`Report`](super::Report) comes back with the template because it is
/// half the answer: a bundled format may have gaps, and the panel shows them.
pub fn template(id: &str) -> Option<Result<Converted, KsyError>> {
	let entry = find(id)?;
	Some(convert(entry.text, &BundledImports))
}

/// Resolve a `meta/imports` name against the bundled collection.
///
/// The wasm layer hands this to a `.ksy` the reader pasted in, so a file of
/// their own that says `imports: [/common/vlq_base128_le]` finds the same text
/// the shipped formats do.
pub struct BundledImports;

impl Imports for BundledImports {
	fn load(&self, name: &str) -> Option<String> {
		let want = name.trim_start_matches('/');
		let by_path = BUNDLED.iter().find(|b| b.source.trim_end_matches(".ksy") == want);
		let base = want.rsplit('/').next().unwrap_or(want);
		by_path.or_else(|| BUNDLED.iter().find(|b| b.id == base)).map(|b| b.text.to_string())
	}
}

/// Which bundled format, if any, claims a file that opens with these bytes,
/// as the `ksy:` name it is opened by.
///
/// Only what a format says out loud counts: the first thing it reads has to be
/// a `contents` at offset 0, nested types looked through, and the pattern is
/// that magic plus every further magic reachable through fields of a fixed
/// width. A format whose magic another bundled format shares claims nothing
/// here, because picking either would be a guess; [`sniff_named`] is where the
/// file's extension gets to settle that.
///
/// This is asked after every built-in probe, so a builtin's answer always
/// wins: see `formats::recognise::PROBES`.
pub fn sniff(head: &[u8]) -> Option<&'static str> {
	BUNDLED
		.iter()
		.find(|b| b.sniffs && matches(b.signature, head))
		.map(|b| b.name)
}

/// [`sniff`], and then, for a file whose bytes fit two bundled formats that
/// share a magic, the one whose `meta/file-extension` is the file's own.
///
/// The bytes still have the first word: a format only comes into it when its
/// whole signature fits the file, and the extension only chooses among those.
/// ESRI's `.shp` and `.shx` are the case in point: the same file code and the
/// same hundred-byte header, told apart by nothing but their names. `ext` is
/// the extension without the dot; case does not matter. `None` when the
/// bytes fit no format, or when the extension picks none or several of the
/// ones they fit.
pub fn sniff_named(head: &[u8], ext: &str) -> Option<&'static str> {
	if let Some(name) = sniff(head) {
		return Some(name);
	}
	let mut fits = BUNDLED.iter().filter(|b| {
		b.offered
			&& enough(b.signature)
			&& matches(b.signature, head)
			&& b.extensions.iter().any(|e| e.eq_ignore_ascii_case(ext))
	});
	match (fits.next(), fits.next()) {
		(Some(b), None) => Some(b.name),
		_ => None,
	}
}

fn matches(signature: &[(u64, &[u8])], head: &[u8]) -> bool {
	!signature.is_empty()
		&& signature.iter().all(|(at, bytes)| {
			let at = *at as usize;
			head.get(at..at + bytes.len()) == Some(*bytes)
		})
}

/// The two-byte rule: a one-byte magic claims every file whose first byte
/// happens to match, which is a guess dressed as an answer.
fn enough(signature: &[(u64, &[u8])]) -> bool {
	signature.iter().map(|(_, b)| b.len()).sum::<usize>() >= 2
}

