//! The eBPF instruction set: what each opcode byte means, and the helper
//! functions a `call` can name.
//!
//! The table is RFC 9669's instruction registry, appendix A, transcribed as
//! written. A row pins the fields that have to hold a particular value for
//! that meaning: `mov` is one opcode whose offset says whether the move sign
//! extends, and the atomic operations are two opcodes whose immediate says
//! which operation. `None` is the registry's "any", a field the opcode leaves
//! free.
//!
//! The forms are the registry's own descriptions, with `dst`, `src`, `imm`,
//! `offset` and `next_imm` left standing. Substituting the registers and
//! numbers an instruction actually holds is what [`super::bpf_disasm`] does,
//! so the line a person reads and the line the standard writes are the same
//! sentence.

/// One row of the instruction registry.
pub struct Op {
    pub code: u8,
    /// The source register field, when the opcode uses it to say which
    /// meaning it has rather than which register to read.
    pub src: Option<u8>,
    pub off: Option<i16>,
    pub imm: Option<i32>,
    /// What the instruction does, in the registry's words.
    pub form: &'static str,
}

