/// What this instruction does, as the registry writes it. The rows that pin
/// the most fields are asked first, so `dst = (s64) (s8) src` wins over
/// `dst = src` for the same opcode with an offset of 8.
pub fn form(code: u8, src: u8, off: i16, imm: i32) -> Option<&'static str> {
    let mut best: Option<(u8, &'static str)> = None;
    for op in OPS.iter().filter(|op| op.code == code) {
        if op.src.is_some_and(|v| v != src) || op.off.is_some_and(|v| v != off) || op.imm.is_some_and(|v| v != imm) {
            continue;
        }
        let pinned = op.src.is_some() as u8 + op.off.is_some() as u8 + op.imm.is_some() as u8;
        if best.is_none_or(|(b, _)| pinned > b) {
            best = Some((pinned, op.form));
        }
    }
    best.map(|(_, form)| form)
}

/// Whether the opcode takes sixteen bytes rather than eight. Only the load of
/// a 64-bit immediate does, and the eight bytes after it are a second
/// instruction word holding the top half of the number.
pub fn is_wide(code: u8) -> bool {
    code == 0x18
}

