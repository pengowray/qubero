/// The run with the table undone, and one step over the whole of it: byte `i`
/// of what comes out is byte `i` of the run, looked up.
pub fn unscramble(data: &[u8]) -> Result<(Vec<u8>, Trace), Refusal> {
    let out = data.iter().map(|&b| UNSCRAMBLE[b as usize]).collect();
    Ok((out, frames::whole(data.len(), data.len())))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_byte_comes_from_exactly_one_scrambled_byte() {
        let mut seen = [false; 256];
        for &b in &UNSCRAMBLE {
            assert!(!seen[b as usize], "0x{b:02x} comes out twice");
            seen[b as usize] = true;
        }
    }

    #[test]
    fn erased_flash_stays_erased() {
        assert_eq!(UNSCRAMBLE[0x00], 0x00);
        assert_eq!(UNSCRAMBLE[0xff], 0xff);
    }

    #[test]
    fn an_i_mx_boot_header_comes_back_out_of_the_noise() {
        // The first four bytes of a Portacapture X8 image as the update file
        // holds them, and the `FCFB` tag of the FlexSPI configuration block
        // they stand for.
        let (out, _) = unscramble(&[0x32, 0x3e, 0x32, 0x3d]).unwrap();
        assert_eq!(out, b"FCFB");
    }
}
