// Bundles the Rubin Observatory's alert schemas into the core, so that an
// alert written in the Confluent wire format, which names its schema by number
// and carries none of it, can still be read.
//
//   node tools/alert_schemas.mjs
//
// The schemas are lsst/alert_packet's, GPL-3.0, and are copied byte for byte
// into crates/core/formats-avro/alert_packet with the repository's LICENSE and
// COPYRIGHT beside them. This writes crates/core/src/formats/avro_alerts.rs,
// the table the reader looks a schema up in. To update: change COMMIT below
// and run this again.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/** The alert_packet commit these schemas come from. Bump to update. */
const COMMIT = "1362a8d7f1db4014cbd419390580a707141c683a";
const REPO = "https://github.com/lsst/alert_packet";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "crates", "core", "formats-avro", "alert_packet");
const TABLE = join(ROOT, "crates", "core", "src", "formats", "avro_alerts.rs");
const WORK = join(ROOT, "target", "alert-packet-checkout");
const TARBALL_NAME = `alert_packet-${COMMIT}.tar.gz`;
const TARBALL = join(ROOT, "target", TARBALL_NAME);

// A tarball rather than a git fetch, for the reason tools/die.mjs gives.
const url = `${REPO}/archive/${COMMIT}.tar.gz`;
const res = await fetch(url);
if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url} - is commit ${COMMIT} still in the repository?`);
mkdirSync(dirname(TARBALL), { recursive: true });
writeFileSync(TARBALL, Buffer.from(await res.arrayBuffer()));

rmSync(WORK, { recursive: true, force: true });
mkdirSync(WORK, { recursive: true });
const top = `alert_packet-${COMMIT}`;
const members = [`${top}/python/lsst/alert/packet/schema`, `${top}/LICENSE`, `${top}/COPYRIGHT`];
execFileSync("tar", ["-xzf", join("..", TARBALL_NAME), "--strip-components", "1", ...members], { cwd: WORK, stdio: "inherit" });

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
copyFileSync(join(WORK, "LICENSE"), join(OUT, "LICENSE"));
copyFileSync(join(WORK, "COPYRIGHT"), join(OUT, "COPYRIGHT"));

// Every version is a directory <major>/<minor>, and its schema ID is
// major * 100 + minor, which is what alert_packet's Schema.get_schema_id says.
const from = join(WORK, "python", "lsst", "alert", "packet", "schema");
const isDir = (p) => statSync(p).isDirectory();
const numbers = (dir) => readdirSync(dir).filter((n) => /^\d+$/.test(n) && isDir(join(dir, n))).map(Number).sort((a, b) => a - b);
const rows = [];
for (const major of numbers(from)) {
  for (const minor of numbers(join(from, String(major)))) {
    const dir = join(from, String(major), String(minor));
    const names = readdirSync(dir).filter((n) => n.endsWith(".avsc")).sort();
    mkdirSync(join(OUT, String(major), String(minor)), { recursive: true });
    for (const name of names) {
      copyFileSync(join(dir, name), join(OUT, String(major), String(minor), name));
      rows.push({ id: major * 100 + minor, path: `${major}/${minor}/${name}`, name });
    }
  }
}

const lines = [
  "//! Rubin's alert schemas, from lsst/alert_packet. Generated by",
  "//! `node tools/alert_schemas.mjs`; do not edit.",
  "//!",
  "//! The files are in `crates/core/formats-avro/alert_packet`, byte for byte as",
  "//! published, under GPL-3.0 (see the LICENSE there and THIRD-PARTY-NOTICES.md).",
  "",
  "/// The alert_packet commit the files were copied from. Only a test reads it,",
  "/// to check it is the commit the script names.",
  "#[cfg_attr(not(test), allow(dead_code))]",
  `pub(super) const COMMIT: &str = "${COMMIT}";`,
  "",
  "/// Each file: the schema ID of the version it belongs to, its name, and its",
  "/// text. A version is several files that name each other's types.",
  "pub(super) const SCHEMAS: &[(i128, &str, &str)] = &[",
  ...rows.map((r) => `    (${r.id}, "${r.name}", include_str!("../../formats-avro/alert_packet/${r.path}")),`),
  "];",
  "",
];
writeFileSync(TABLE, lines.join("\n"), "utf8");
const versions = new Set(rows.map((r) => r.id));
console.log(`${rows.length} files in ${versions.size} versions, from ${REPO} at ${COMMIT}`);
